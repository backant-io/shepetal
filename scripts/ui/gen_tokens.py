#!/usr/bin/env python3
"""Writes Sources/Shepetal/UI/Tokens.swift from design/ui/tokens.json.

    python3 -I scripts/ui/gen_tokens.py          # rewrite the Swift file
    python3 -I scripts/ui/gen_tokens.py --check  # exit 1 if it is out of date

Tests/ShepetalTests/UITokenTests.swift reads tokens.json on its own and fails when a Swift value drifts from it,
so a hand edit to Tokens.swift or a new tokens.json without a rerun turns the swift suite red.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "design/ui/tokens.json"
OUT = ROOT / "Sources/Shepetal/UI/Tokens.swift"


def camel(name: str) -> str:
    parts = name.removeprefix("sh-").split("-")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def hex_rgba(value: str) -> str:
    h = value.lstrip("#").upper()
    if len(h) == 6:
        h += "FF"
    assert re.fullmatch(r"[0-9A-F]{8}", h), value
    return "0x" + h


def px(value: str) -> str:
    m = re.fullmatch(r"(-?[\d.]+)px", value)
    assert m, value
    return m.group(1)


def num(v: float) -> str:
    s = repr(float(v))
    return s[:-2] if s.endswith(".0") else s


def shadow_layers(css: str) -> str:
    layers = []
    for part in re.split(r",\s*(?![^()]*\))", css):
        part = part.strip()
        inset = part.startswith("inset ")
        part = part.removeprefix("inset ").strip()
        m = re.fullmatch(r"((?:-?[\d.]+(?:px)?\s+){2,4})(.+)", part)
        assert m, css
        lengths = [float(x.removesuffix("px")) for x in m.group(1).split()]
        lengths += [0] * (4 - len(lengths))
        color = m.group(2).strip()
        if color.startswith("#"):
            rgba = hex_rgba(color)
        else:
            c = re.fullmatch(r"rgba\(([\d.]+),\s*([\d.]+),\s*([\d.]+),\s*([\d.]+)\)", color)
            assert c, color
            r, g, b = (int(c.group(i)) for i in (1, 2, 3))
            a = round(float(c.group(4)) * 255)
            rgba = f"0x{r:02X}{g:02X}{b:02X}{a:02X}"
        x, y, blur, spread = lengths
        layers.append(f"SHShadowLayer(inset: {str(inset).lower()}, x: {num(x)}, y: {num(y)}, blur: {num(blur)}, "
                      f"spread: {num(spread)}, rgba: {rgba})")
    return "[" + ", ".join(layers) + "]"


def generate() -> str:
    t = json.loads(SRC.read_text())
    ramp = {c["name"]: c["value"] for c in t["color"]["tokens"] if isinstance(c["value"], str) and "{" not in c["value"]}

    def resolve(v: str) -> str:
        m = re.fullmatch(r"\{(.+)\}", v)
        return hex_rgba(ramp[m.group(1)] if m else v)

    out = ["// Generated by scripts/ui/gen_tokens.py from design/ui/tokens.json. Do not edit: change tokens.json and",
           "// run `python3 -I scripts/ui/gen_tokens.py`. UITokenTests fails when a value here drifts from tokens.json.",
           "import CoreGraphics", "", "extension SH {"]
    colors, lets = [], []
    out.append("    // MARK: colors (Concrete, Night)")
    for c in t["color"]["tokens"]:
        v = c["value"]
        light, dark = (resolve(v), resolve(v)) if isinstance(v, str) else (resolve(v["light"]), resolve(v["dark"]))
        out.append(f'    static let {camel(c["name"])} = SHColor("{c["name"]}", light: {light}, dark: {dark})')
        colors.append(camel(c["name"]))

    def scalar_group(key: str, label: str, conv):
        names = []
        out.append(f"\n    // MARK: {label}")
        for tok in t[key]["tokens"]:
            v = conv(tok["value"])
            if v is None:
                continue
            out.append(f'    static let {camel(tok["name"])}: CGFloat = {v}')
            names.append(tok["name"])
        return names

    space = scalar_group("spacing", "spacing (pt)", px)
    radius = scalar_group("radius", "radius (pt)", px)
    travel = scalar_group("travel", "travel (pt)", px)
    size = scalar_group("size", "sizes (pt); sh-measure is in ch and has no point value",
                        lambda v: px(v) if v.endswith("px") else None)

    out.append("\n    // MARK: layers")
    layer = []
    for tok in t["layer"]["tokens"]:
        out.append(f'    static let {camel(tok["name"])} = {int(tok["value"])}')
        layer.append(tok["name"])

    out.append("\n    // MARK: durations (seconds)")
    dur = []
    for tok in t["duration"]["tokens"]:
        m = re.fullmatch(r"(\d+)ms", tok["value"])
        out.append(f'    static let {camel(tok["name"])}: Double = {int(m.group(1)) / 1000}')
        dur.append(tok["name"])

    out.append("\n    // MARK: easings")
    ease = []
    for tok in t["easing"]["tokens"]:
        m = re.fullmatch(r"cubic-bezier\(([^)]*)\)", tok["value"])
        a = [num(float(x)) for x in m.group(1).split(",")]
        out.append(f'    static let {camel(tok["name"])} = SHEasing(x1: {a[0]}, y1: {a[1]}, x2: {a[2]}, y2: {a[3]})')
        ease.append(tok["name"])

    out.append("\n    // MARK: shadows (Concrete, Night)")
    shadows = []
    for tok in t["shadow"]["tokens"]:
        v = tok["value"]
        out.append(f'    static let {camel(tok["name"])} = SHShadow(\n        "{tok["name"]}",\n'
                   f'        light: {shadow_layers(v["light"])},\n        dark: {shadow_layers(v["dark"])})')
        shadows.append(tok["name"])

    out.append("\n    // MARK: type styles (pt; line heights given as a ratio are multiplied out)")
    styles = []
    for group in t["type"]["groups"]:
        fam = {"ui": ".ui", "mono": ".mono", "serif": ".serif"}[group["family"]]
        for s in group["styles"]:
            size_pt = float(px(s["fontSize"]))
            lh = s["lineHeight"]
            lh_pt = float(px(lh)) if isinstance(lh, str) else round(size_pt * lh, 3)
            ls = s.get("letterSpacing", "0em")
            m = re.fullmatch(r"(-?[\d.]+)em", ls)
            italic = str(s.get("fontStyle") == "italic").lower()
            out.append(f'    static let {camel(s["name"])} = SHTextStyle("{s["name"]}", family: {fam}, size: {num(size_pt)}, '
                       f'lineHeight: {num(lh_pt)}, weight: {s["fontWeight"]}, tracking: {num(float(m.group(1)))}, italic: {italic})')
            styles.append(s["name"])
    out.append("}")

    def table(name: str, typ: str, names: list[str]) -> str:
        rows = ",\n".join(f'        ("{n}", SH.{camel(n)})' for n in names)
        return f"    static let {name}: [(name: String, value: {typ})] = [\n{rows},\n    ]"

    out += ["", "/// Every token above by its tokens.json name, for UITokenTests and the Gallery.", "enum SHTokens {",
            "    static let colors: [SHColor] = [" + ", ".join(f"SH.{c}" for c in colors) + "]",
            table("space", "CGFloat", space), table("radius", "CGFloat", radius),
            table("travel", "CGFloat", travel), table("size", "CGFloat", size),
            table("layer", "Int", layer), table("duration", "Double", dur), table("easing", "SHEasing", ease),
            "    static let shadows: [SHShadow] = [" + ", ".join(f"SH.{camel(n)}" for n in shadows) + "]",
            "    static let textStyles: [SHTextStyle] = [" + ", ".join(f"SH.{camel(n)}" for n in styles) + "]",
            "}", ""]
    return "\n".join(out)


def main() -> int:
    text = generate()
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python3 -I scripts/ui/gen_tokens.py")
            return 1
        print(f"{OUT.relative_to(ROOT)} matches tokens.json")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
