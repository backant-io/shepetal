#!/usr/bin/env node
// Writes the landing page's scroll CSS from the one timing table (src/components/story/choreography.ts).
//   node scripts/story-css.mjs     (Node 22.18 or later runs the .ts file as is)
// choreography.test.ts fails while the committed file differs from the table.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { storyCss } from '../src/components/story/choreography.ts';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'components', 'story', 'story.generated.css');
writeFileSync(out, `/* Generated by scripts/story-css.mjs from choreography.ts. Do not edit. */\n${storyCss()}`);
console.log(`wrote ${out}`);
