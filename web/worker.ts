// The Worker's entry (wrangler.toml main): the host rules first, then what this file answers itself, then OpenNext's
// worker. www.<SHEPETAL_DOMAIN> goes to the apex; the old host (shepetal.backant.io) moves every path, /api/* included,
// to the domain with a 301 (src/lib/site.ts). Static files (the assets binding) are served before this runs.
// The Workers Free plan gives a request 10 ms of CPU, and loading the Next server alone takes more: the releases and
// the app's API calls are answered here, the prerendered pages by OpenNext's routing from their build-time copies
// (open-next.config.ts). Everything else goes to Next.
import { GET as license } from './src/app/api/license/route';
import { POST as revoke } from './src/app/api/app/revoke/route';
import { POST as token } from './src/app/api/app/token/route';
import { analyticsConfig } from './src/lib/analytics-config';
import { releaseRoute } from './src/lib/download';
import { withEdgeHtml } from './src/lib/edge-html';
import { hostRedirect } from './src/lib/site';
import { securityHeaders } from './security-headers.mjs';
// @ts-ignore: generated by `opennextjs-cloudflare build` (absent before the first build), resolved by wrangler
import { runWithCloudflareRequestContext } from './.open-next/cloudflare/init.js';
// @ts-ignore: generated by `opennextjs-cloudflare build` (absent before the first build), resolved by wrangler
import openNext from './.open-next/worker.js';

// @ts-ignore: generated by `opennextjs-cloudflare build`
export { DOQueueHandler, DOShardedTagCache, BucketCachePurge } from './.open-next/worker.js';

type Env = { POSTHOG_KEY?: string; POSTHOG_HOST?: string; RELEASES: R2Bucket };

/** The Next route handlers that need nothing of Next (no next/*, no next-auth), called without it. */
const NATIVE: Record<string, (req: Request) => Promise<Response>> = {
  'GET /api/license': license,
  'POST /api/app/token': token,
  'POST /api/app/revoke': revoke,
};

export default {
  async fetch(request: Request, env: Env, ctx: unknown): Promise<Response> {
    const url = new URL(request.url);
    const moved = hostRedirect(url);
    if (moved) return moved;
    // OpenNext's request context: getCloudflareContext() works, so D1 is there and analytics go out after the answer.
    return runWithCloudflareRequestContext(request, env, ctx, async () => {
      const release = await releaseRoute(env.RELEASES, request);
      if (release) return release;
      const native = NATIVE[`${request.method} ${url.pathname}`];
      if (native) {
        const res = await native(request);
        for (const { key, value } of securityHeaders(analyticsConfig(env).host)) res.headers.set(key, value);
        return res;
      }
      return withEdgeHtml(await openNext.fetch(request, env, ctx), env, url);
    });
  },
};
