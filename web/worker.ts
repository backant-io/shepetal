type Env = { POSTHOG_KEY?: string; POSTHOG_HOST?: string; RELEASES: R2Bucket; CF_VERSION_METADATA: WorkerVersionMetadata };

/** The Next route handlers that need nothing of Next (no next/*, no next-auth), called without it. */
const NATIVE: Record<string, (req: Request) => Promise<Response>> = {
  'GET /api/license': license,
  'POST /api/app/token': token,
  'POST /api/app/revoke': revoke,
  // The "Jetzt kündigen" button (/cancel): open to everyone, with no sign-in.
  'POST /api/cancel': cancel,
};

export default {
  async fetch(request: Request, env: Env, ctx: ExecutionContext): Promise<Response> {
    const url = new URL(request.url);
    const moved = hostRedirect(url);
    if (moved) return moved;
    // OpenNext's request context: getCloudflareContext() works, so D1 is there and analytics go out after the answer.
    return runWithCloudflareRequestContext(request, env, ctx, async () => {
      const release = await releaseRoute(env.RELEASES, request);
      if (release) return release;
      const native = NATIVE[`${request.method} ${url.pathname}`];
      if (native) {
        const res = await native(request);
        for (const { key, value } of securityHeaders(analyticsConfig(env).host)) res.headers.set(key, value);
        return res;
      }
      // What OpenNext served from a prerendered copy, kept in this data center's cache: on the landing page, reading
      // its 403 KB build-time copy took about 4 of the 10 ms. The cache does not work on workers.dev previews.
      const key = cacheKey(request, url, env);
      const cached = key && (await edgeCache().match(key));
      if (cached) return withEdgeHtml(cached, env, url);
      const res: Response = await openNext.fetch(request, env, ctx);
      if (key && res.status === 200 && res.headers.get('x-opennext-cache') === 'HIT') ctx.waitUntil(edgeCache().put(key, res.clone()));
      return withEdgeHtml(res, env, url);
    });
  },
};

/** The prerendered pages (robots.txt and the sitemap answer with max-age=0, which the cache does not keep). */
const PAGES = new Set(Object.entries(prerendered.routes as Record<string, { dataRoute: string | null }>).filter(([, r]) => r.dataRoute).map(([p]) => p));

// The data center's cache (tsconfig's DOM lib types `caches` without Workers' `default`)
const edgeCache = () => (caches as unknown as { default: Cache }).default;

/**
 * The cache key of a GET that OpenNext may answer from a prerendered copy: the version (a deploy never serves an old
 * page), the path, and which of the copy's bodies it gets, as OpenNext picks it: the page, or with `rsc: 1` the RSC
 * payload or the one segment next-router-segment-prefetch names. The query plays no part in a prerendered page.
 */
function cacheKey(req: Request, url: URL, env: Env): string | null {
  // A lookup that always misses (a 404, an API, a dynamic page) cost about 2 ms of CPU on the preview.
  if (req.method !== 'GET' || !PAGES.has(url.pathname)) return null;
  const body = req.headers.get('rsc') === '1' ? (req.headers.get('next-router-segment-prefetch') ?? 'rsc') : 'html';
  return `${url.origin}${url.pathname}?prerendered=${env.CF_VERSION_METADATA.id}:${encodeURIComponent(body)}`;
}
