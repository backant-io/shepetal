type Env = LifecycleEnv & { POSTHOG_KEY?: string; POSTHOG_HOST?: string; RELEASES: R2Bucket; CF_VERSION_METADATA: WorkerVersionMetadata };

/** The Next route handlers that need nothing of Next (no next/*), called without it: every API, sign-in included. */
const NATIVE: Partial<Record<string, (req: Request) => Promise<Response>>> = {
  'GET /app/login': appLogin,
  'POST /app/login': appConsent,
  'POST /api/auth/signin/google': signInPost,
  'GET /api/auth/callback/google': googleCallback,
  'POST /api/auth/signout': signOutPost,
  'GET /api/auth/providers': providers,
  'GET /api/account': account,
  'GET /api/account/plan': plan,
  'POST /api/checkout': checkout,
  'GET /api/billing/portal': portalLink,
  'POST /api/billing/portal': portal,
  'POST /api/billing/cancel': billingCancel,
  'POST /api/billing/resume': billingResume,
  'POST /api/stripe/webhook': stripeWebhook,
  'GET /api/license': license,
  'POST /api/app/token': token,
  'POST /api/app/revoke': revoke,
  // The "Jetzt kündigen" button (/cancel): open to everyone, with no sign-in.
  'POST /api/cancel': cancel,
  // The waitlist (src/lib/waitlist.ts): the form, the confirmation link, and the unsubscribe page and one-click POST.
  // With WAITLIST off the first two answer 404 and touch nothing.
  'POST /api/waitlist': waitlist,
  'GET /api/waitlist/confirm': waitlistConfirm,
  'GET /api/waitlist/unsubscribe': waitlistUnsubscribePage,
  'POST /api/waitlist/unsubscribe': waitlistUnsubscribe,
  // The link in every trial email: GET asks, POST (the button, or the mail app's one-click) unsubscribes.
  'GET /unsubscribe': unsubscribe,
  'POST /unsubscribe': unsubscribe,
};

export default {
  async fetch(request: Request, env: Env, ctx: ExecutionContext): Promise<Response> {
    const url = new URL(request.url);
    const moved = hostRedirect(url);
    if (moved) return moved;
    const api = url.pathname.startsWith('/api/');
    const native = NATIVE[`${request.method} ${url.pathname}`];
    // An exception anywhere below is the site's own 500 with the security headers, never Cloudflare's 1101 page.
    const route = `${request.method} ${native ? url.pathname : api ? '/api/*' : 'page'}`;
    // OpenNext's request context: getCloudflareContext() works, so D1 is there and analytics go out after the answer.
    return guarded(route, api, () => runWithCloudflareRequestContext(request, env, ctx, async () => {
      const release = await releaseRoute(env.RELEASES, request);
      if (release) return release;
      if (native) {
        const res = secured(await native(request));
        serverEvents(request, url, res, env, ctx); // the app sign-in steps (/app/login)
        return res;
      }
      // Nothing else may load the Next server (more CPU than a request gets): any other API path or method is a 404,
      // and a page answers GET and HEAD only (a stale server action POST included).
      if (url.pathname.startsWith('/api/')) return secured(Response.json({ error: 'not_found' }, { status: 404 }));
      if (request.method !== 'GET' && request.method !== 'HEAD') return secured(new Response('Method Not Allowed', { status: 405, headers: { allow: 'GET, HEAD' } }));
      // Per-visit decisions on the static pages, before the cache: /login signed in and /account signed out redirect.
      const page = request.method === 'GET' && request.headers.get('rsc') !== '1';
      const to = page ? await pageRedirect(request, url) : null;
      if (to) return secured(to);
      // /changelog lists the releases on R2 as they are now.
      const releases = page && url.pathname === '/changelog' ? releasesHtml(await releasesOf(env.RELEASES).catch(() => [])) : undefined;
      // What OpenNext served from a prerendered copy, kept in this data center's cache: on the landing page, reading
      // its 403 KB build-time copy took about 4 of the 10 ms. The cache does not work on workers.dev previews.
      const key = cacheKey(request, url, env);
      const cached = key && (await edgeCache().match(key));
      const res: Response = cached || (await openNext.fetch(request, env, ctx));
      if (key && !cached && res.status === 200 && res.headers.get('x-opennext-cache') === 'HIT') ctx.waitUntil(edgeCache().put(key, res.clone()));
      const out = withEdgeHtml(res, url, releases);
      serverEvents(request, url, out, env, ctx);
      return out;
    }));
  },

  // The Cron Trigger (wrangler.toml [triggers], once a day at 03:15 UTC while the trial emails are off): the trial
  // emails (LIFECYCLE_EMAILS "off": nothing sent), at most 5 a run. No Next here.
  // On the 03:15 UTC run, also the waitlist sweep: rows that are not confirmed go 29 days after their last
  // signup, so the privacy policy's 30 days hold. It runs with the waitlist off too: rows from a time it was on still go.
  async scheduled(controller: ScheduledController, env: Env, ctx: ExecutionContext): Promise<void> {
    ctx.waitUntil(runLifecycle(env));
    const at = new Date(controller.scheduledTime);
    if (at.getUTCHours() === 3 && at.getUTCMinutes() === 15)
      ctx.waitUntil(
        sweep(env.DB).then(
          (n) => console.log(JSON.stringify({ waitlist_swept: n })),
          (e) => console.error('waitlist: sweep failed', scrub(e)),
        ),
      );
  },
};

/** The prerendered pages (robots.txt and the sitemap answer with max-age=0, which the cache does not keep). */
const PAGES = new Set(Object.entries(prerendered.routes as Record<string, { dataRoute: string | null }>).filter(([, r]) => r.dataRoute).map(([p]) => p));

// The data center's cache (tsconfig's DOM lib types `caches` without Workers' `default`)
const edgeCache = () => (caches as unknown as { default: Cache }).default;

/**
 * The cache key of a GET that OpenNext may answer from a prerendered copy: the version (a deploy never serves an old
 * page), the path, and which of the copy's bodies it gets, as OpenNext picks it: the page, or with `rsc: 1` the RSC
 * payload or the one segment next-router-segment-prefetch names. The query plays no part in a prerendered page.
 */
function cacheKey(req: Request, url: URL, env: Env): string | null {
  // A lookup that always misses (a 404, an API, a dynamic page) cost about 2 ms of CPU on the preview.
  if (req.method !== 'GET' || !PAGES.has(url.pathname)) return null;
  const body = req.headers.get('rsc') === '1' ? (req.headers.get('next-router-segment-prefetch') ?? 'rsc') : 'html';
  return `${url.origin}${url.pathname}?prerendered=${env.CF_VERSION_METADATA.id}:${encodeURIComponent(body)}`;
}
